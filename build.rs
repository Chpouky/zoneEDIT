//! Generates the table of the embedded icons (`assets/icons/*.png`, named by
//! item SID): `OUT_DIR/icons_table.rs` is included by `src/ui/icons.rs`.
//!
//! The icons are extracted from `InventoryUIExports/` via the root script
//! `match_icons.py` (SID -> icon mapping from the game's .cfg).
//! The native dimensions (PNG header) are also emitted: the layout
//! (`metrics.rs`) depends on them for the icon box.

use std::env;
use std::fs;
use std::path::PathBuf;

/// Width/height of a PNG from its header (no decoding).
fn png_size(path: &PathBuf) -> Option<(u32, u32)> {
    let b = fs::read(path).ok()?;
    if b.len() < 24 || &b[12..16] != b"IHDR" {
        return None;
    }
    let w = u32::from_be_bytes(b[16..20].try_into().ok()?);
    let h = u32::from_be_bytes(b[20..24].try_into().ok()?);
    Some((w, h))
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icons_dir = manifest.join("assets").join("icons");
    // Watch the directory AND each file: the directory-only watch is
    // unreliable for *added* files (build.rs does not re-run).
    println!("cargo:rerun-if-changed={}", icons_dir.display());

    let mut entries: Vec<(String, PathBuf, u32, u32)> = Vec::new();
    for entry in fs::read_dir(&icons_dir).expect("read assets/icons") {
        let entry = entry.expect("assets/icons entry");
        let path = entry.path();
        if !path.is_file()
            || !path
                .extension()
                .is_some_and(|e| e.eq_ignore_ascii_case("png"))
        {
            continue;
        }
        let Some((w, h)) = png_size(&path) else {
            continue;
        };
        if h == 0 {
            continue;
        }
        let sid = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default()
            .to_string();
        entries.push((sid, path, w, h));
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    for (_, path, _, _) in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let out_file = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("icons_table.rs");
    let mut s = String::from("// Generated by build.rs — do not edit.\n\n");
    s.push_str("pub const TABLE: &[(&str, &[u8], u32, u32)] = &[\n");
    for (sid, path, w, h) in &entries {
        // Forward slashes: `include_bytes!` takes a string literal, where
        // the backslashes of a Windows path (`D:\a\zoneEDIT\…`) would be
        // parsed as character escapes and fail to compile.
        let p = path.to_string_lossy().replace('\\', "/");
        s.push_str(&format!(
            "    (\"{sid}\", include_bytes!(\"{p}\"), {w}, {h}),\n"
        ));
    }
    s.push_str("];\n");
    fs::write(&out_file, s).expect("write icons_table.rs");
}
